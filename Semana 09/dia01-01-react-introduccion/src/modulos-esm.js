// ESM  es una forma de importar y exportar módulos en JavaScript. ESM significa "ECMAScript Modules" y es la forma estándar de trabajar con módulos en JavaScript moderno. A continuación, se muestra un ejemplo de cómo importar y exportar módulos utilizando ESM:
//podemos dividir el código en varios archivos y luego importarlos según sea necesario. Esto ayuda a mantener el código organizado y modular.

import miNombre, { frutas, curso } from "./modulo"; /// Importamos el array de frutas desde el archivo modulo.js

console.log(frutas) // Esto imprimirá el array de frutas en la consola
console.log(miNombre) // Esto imprimirá el nombre "Juan" en la consola 
console.log(curso) // Esto imprimirá el objeto curso en la consola 